#!/bin/bash
# deploy.sh - Simplified profile-based build

# Validate SECRET_SSID and SECRET_PASS environment variables
if [ -z "$SECRET_SSID" ] || [ -z "$SECRET_PASS" ]; then
    echo "======================================================="
    echo "ERROR: SECRET_SSID or SECRET_PASS environment variables are missing!"
    echo "======================================================="
    echo "You must specify SECRET_SSID and SECRET_PASS environment variables when calling this script."
    echo ""
    echo "Usage:"
    echo "  SECRET_SSID=<ssid> SECRET_PASS=<pass> $0 [options] [port]"
    echo ""
    echo "Examples:"
    echo "  SECRET_SSID=MyWiFi SECRET_PASS=MyPassword $0"
    echo "  SECRET_SSID=MyWiFi SECRET_PASS=MyPassword $0 /dev/ttyACM0"
    echo "  SECRET_SSID=MyWiFi SECRET_PASS=MyPassword $0 --compile-only"
    echo ""
    exit 1
fi

# We use FQBN instead of PROFILE to allow using the --libraries flag for local paths
FQBN="esp32:esp32:lilygo_t_display_s3:CDCOnBoot=cdc,USBMode=hwcdc,PartitionScheme=app3M_fat9M_16MB"
PORT="/dev/ttyACM0"
CLI_EXE="/app/arduino-ide/resources/app/lib/backend/resources/arduino-cli"
COMPILE_ONLY=false

# Simple argument parsing
for arg in "$@"; do
  case $arg in
    --compile-only|-c)
      COMPILE_ONLY=true
      shift
      ;;
    *)
      # If it's not a flag, assume it's the port
      if [[ -e "$arg" || "$arg" == /dev/* ]]; then
        PORT="$arg"
      fi
      ;;
  esac
done

# Move to the source directory so arduino-cli compiles the src sketch
cd "$(dirname "$0")/../server-firmware" || exit 1

# Load local environment overrides if present
if [ -f "../.deploy.env" ]; then
    source ../.deploy.env
fi

# Dynamically generate Config.cpp using the environment variables
echo "Generating Secrets.cpp with SSID and PASS..."
cat << EOF > Secrets.cpp
// AUTO-GENERATED BY deploy.sh - DO NOT EDIT THIS FILE
#include "Secrets.h"

const char* SECRET_SSID = "${SECRET_SSID}";
const char* SECRET_PASS = "${SECRET_PASS}";
EOF

# Load extra flags from central file, stripping comment lines and joining into one line
TFT_FLAGS=$(grep -v '^\s*#' extra_flags.txt | tr '\n' ' ')

echo "-------------------------------------------------------"
echo "STEP 1: Compiling using FQBN: $FQBN..."

# Use a relative build path instead of a hardcoded absolute path
build_path=../build

# Profiles in sketch.yaml often ignore build_properties for libraries, 
# so we pass them explicitly here to ensure display stability.
flatpak run --command=sh cc.arduino.IDE2 -c "$CLI_EXE compile $EXTRA_LIBS --fqbn $FQBN --build-path $build_path --build-property \"build.extra_flags=$TFT_FLAGS\" ."

if [ $? -eq 0 ]; then
    echo "SUCCESS: Compilation finished."
    
    if [ "$COMPILE_ONLY" = true ]; then
        echo "Skipping upload as requested."
        exit 0
    fi

    echo "STEP 2: Uploading to $PORT..."
    flatpak run --command=sh cc.arduino.IDE2 -c "$CLI_EXE upload --build-path $build_path --fqbn $FQBN --port $PORT ."
else
    echo "FAILED: Compilation errors."
    exit 1
fi
